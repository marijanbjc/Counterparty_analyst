FOCUSED_HEADER = (
    "Ниже — углублённые разборы по направлениям, посчитанные кодом. "
    "Тезисы уже готовы, пересчитывать их и вызывать run_focused_analysis повторно не нужно."
)


def skeleton(keys: tuple[str, ...]) -> str:
    """Скелет ответа — та же схема, что проверяет check_shape, но для модели.

    Строится из тех же констант: разойтись описанию и проверке негде.
    """
    lines = []
    for key in keys:
        if key == CONTRACTORS:
            item = f'{{"inn": "…", "{KEY_RISKS}": ["…"], "{POSITIVES}": ["…"]}}'
            lines.append(f'  "{key}": [{item}, …]')
        elif key in LIST_KEYS:
            lines.append(f'  "{key}": ["…", "…"]')
        else:
            lines.append(f'  "{key}": "…"')
    return "{\n" + ",\n".join(lines) + "\n}"


def system(keys: tuple[str, ...], role: str = "general", with_tools: bool = False) -> str:
    if CONTRACTORS in keys:
        shape = _COMPARE_SHAPE
    else:
        shape = _REPORT_SHAPE if len(keys) > 1 else _REPLY_SHAPE
    parts = [RULES, ROLE_RULES.get(role, ROLE_RULES["general"])]
    if with_tools:
        parts.append(TOOLS_RULES)
    parts.append(_FORMAT.format(skeleton=skeleton(keys)))
    parts.append(shape)
    return "\n\n".join(parts)


# Наборы приходят из кнопок, а не из базового пакета, и модель обязана видеть
# разницу: иначе она принимает дочитанное за часть отчёта и ссылается на него
# как на то, что было известно с самого начала.
# Формулировка проверена на живой модели: с ней разбор приходит полным. Попытка
# усилить её требованием «назови значения из набора в analysis» вернула пустой
# analysis и completion вдвое длиннее — давить на модель здесь нельзя.
SETS_HEADER = (
    "Ниже — наборы данных, дочитанные по кнопкам, которые пользователь отметил в этом "
    "сообщении. Это не часть базового факт-пакета, а ответ на его отдельный запрос: "
    "разбери их наравне с пакетом и опирайся на их цифры, а не на общие слова. "
    "Правила выше действуют на них полностью — ничего, кроме переданного, "
    "и null здесь по-прежнему «данных нет», а не ноль."
)


def analyze_block(message: str, verdict: dict[str, Any], fact_pack: dict[str, Any]) -> str:
    return "\n".join(
        [
            f"Вопрос пользователя: {message}",
            _verdict_line(verdict),
            f"Факт-пакет контрагента (ИНН {fact_pack['inn']}):",
            json.dumps(fact_pack, ensure_ascii=False),
        ]
    )


# Ключ items содержит compact-пакеты по каждому контрагенту и весит втрое больше
# всей остальной сводки. Коду он нужен — по нему считаются вердикты и обязательные
# упоминания, — а модели нет: всё уже агрегировано в matrix (known_issues.md §3).
COMPARE_SUMMARY_KEYS = ("matrix", "differences", "ranking", "not_comparable", "not_found")


def compare_summary(payload: dict[str, Any]) -> dict[str, Any]:
    return {key: payload[key] for key in COMPARE_SUMMARY_KEYS if key in payload}


def compare_block(message: str, verdicts: list[dict[str, Any]], payload: dict[str, Any]) -> str:
    lines = [f"Вопрос пользователя: {message}", "Вердикты посчитаны кодом, пересматривать их нельзя:"]
    lines += [f"— ИНН {item['inn']}: {item['verdict']}." for item in verdicts]
    lines.append("Сводка сравнения, посчитанная кодом:")
    lines.append(json.dumps(compare_summary(payload), ensure_ascii=False))
    lines.append(
        "Сводного вывода «работайте с этим» не давай: инструмент показывает различия, "
        "выбор делает пользователь."
    )
    return "\n".join(lines)


def clarify_block(message: str, with_tools: bool = False) -> str:
    extra = (
        "Если нужных цифр в контексте нет — вызови инструмент, не выдумывай."
        if with_tools
        else "Если для ответа нужных данных в контексте нет — так и скажи и попроси ИНН."
    )
    return (
        f"Вопрос пользователя: {message}\n"
        "Отвечай по разобранному в этой сессии. Нового отчёта не делай. "
        + extra
    )


def _verdict_line(verdict: dict[str, Any]) -> str:
    line = f"Вердикт, посчитанный кодом: {verdict['verdict']}. Объясни его, не пересматривай."
    if verdict.get("escalated"):
        line += f" Вердикт повышен из-за правового статуса: {verdict['reason']}."
    return line
